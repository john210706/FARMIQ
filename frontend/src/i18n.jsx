export function tr(value, language = activeLanguage) {
  if (value == null || language === 'en') return String(value ?? '');
  const input = String(value),
    trimmed = input.trim();
  let translated = dictionaries[language]?.[trimmed] || enums[language]?.[trimmed];
  if (!translated)
    for (const [pattern, replacement] of patterns[language] || [])
      if (pattern.test(trimmed)) {
        translated = trimmed.replace(pattern, replacement);
        break;
      }
  if (!translated) return input;
  return input.replace(trimmed, translated);
}

export function trError(value, language = activeLanguage) {
  const translated = tr(value, language);
  if (language === 'en' || translated !== String(value)) return translated;
  return language === 'ta'
    ? 'கோரிக்கையை முடிக்க முடியவில்லை. உங்கள் உள்ளீட்டைச் சரிபார்த்து மீண்டும் முயற்சிக்கவும்.'
    : 'अनुरोध पूरा नहीं हो सका। अपनी जानकारी जाँचकर फिर प्रयास करें।';
}

const originals = new WeakMap(),
  rendered = new WeakMap();
function localizeTree(root, language) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName)) continue;
    const previous = rendered.get(node);
    if (!originals.has(node) || (previous !== undefined && node.data !== previous))
      originals.set(node, node.data);
    const next = tr(originals.get(node), language);
    if (node.data !== next) node.data = next;
    rendered.set(node, next);
  }
  for (const element of root.querySelectorAll?.('[placeholder],[aria-label],[title]') || []) {
    for (const attribute of ['placeholder', 'aria-label', 'title'])
      if (element.hasAttribute(attribute)) {
        const key = `i18n${attribute
          .split('-')
          .map((part) => part[0].toUpperCase() + part.slice(1))
          .join('')}`;
        if (!element.dataset[key]) element.dataset[key] = element.getAttribute(attribute);
        element.setAttribute(attribute, tr(element.dataset[key], language));
      }
  }
}

export function Localizer({ language, children }) {
  const ref = useRef(null);
  setLocale(language);
  useLayoutEffect(() => {
    const root = ref.current;
    localizeTree(root, language);
    const observer = new MutationObserver(() => localizeTree(root, language));
    observer.observe(root, { childList: true, subtree: true, characterData: true });
    return () => observer.disconnect();
  }, [language]);
  return (
    <div ref={ref} className="locale-root">
      {children}
    </div>
  );
}
